#!/usr/bin/env python3
"""Render the generated blocks of reference-check.md for issue #139.

Three blocks, each injected between markers and never assembled by hand:

1. **The verification run** (the `verify-receipt` block): the whole stdout of
   `python3 refscan139.py --verify`, the network pass that re-fetched every pool entry from its live
   endpoint and compared the returned title with the stored one.  A quoted output line is a claim
   about a PROGRAM (Class 192), and the pool it is evidence about can move, so the receipt's first
   line names that pool by sha256 and `refscan139.py --gate` fails when the digest no longer matches
   the shipped `refs/pool.json` (Class 230 -- a receipt expires when its object moves).

2. **The journal reference gate's output** (the `journal-refgate` block).  The gate
   (`.github/tools/refgate.py`) is editor-side tooling that lives outside this package, so its
   output is carried as the committed receipt `refgate-journal.txt`, produced by the exact command
   the block's own preamble names -- and `reproduce.sh` re-runs the gate and compares against this
   receipt byte-for-byte whenever the journal checkout is present.  The block quotes the gate's
   **whole** output, verdict line and every advisory line with it, because `GATE: PASS` covers only
   `entries >= 100` and `no uncited entries`; the advisory set is derived from the receipt rather
   than asserted, so a run that does print one cannot be reported as if it did not.

3. **The per-entry table** (the `entries` block): one row per pool entry -- key, source, the method
   that verified it, the result, and the real record the method returned.  The result column is not
   typed: it is rendered from the receipt's verdict, and the block refuses to render unless the
   receipt records a run with no mismatch and no transport failure, so a row cannot claim a
   verification the run did not perform.

`--check` re-renders every block into memory and compares against the shipped file, writing nothing.

Run:  python3 make_reference_check.py            (write reference-check.md, staged then os.replace'd)
      python3 make_reference_check.py --check    (verify the committed report is what this renders)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "reference-check.md")
POOL = os.path.join(HERE, "refs", "pool.json")
RECEIPT = os.path.join(HERE, "refs", "verify-run.txt")
GATE_RECEIPT = os.path.join(HERE, "refgate-journal.txt")
BEGIN = "<!-- verify-receipt:begin (generated by make_reference_check.py -- do not edit by hand) -->"
END = "<!-- verify-receipt:end -->"
GATE_BEGIN = "<!-- journal-refgate:begin (generated by make_reference_check.py -- do not edit by hand) -->"
GATE_END = "<!-- journal-refgate:end -->"
ENT_BEGIN = "<!-- entries:begin (generated by make_reference_check.py -- do not edit by hand) -->"
ENT_END = "<!-- entries:end -->"
CMD = "python3 refscan139.py --verify"
GATE_CMD = "python3 .github/tools/refgate.py papers/issue-139/manuscript.md"


def replace_block(text, begin, end, block):
    """Replace the marked region [begin..end] in `text` with `block`.

    The markers' surrounding newlines belong to the text AROUND the region, not to the block, so
    `block` carries none of them: a block that ends with a newline of its own re-adds one separator
    per run and the rendering stops being idempotent (Class 117)."""
    if begin not in text or end not in text:
        raise SystemExit("the report does not carry the markers %r / %r" % (begin, end))
    head = text.split(begin, 1)[0]
    tail = text.split(end, 1)[1]
    return head + block + tail


def _receipt(path, what):
    if not os.path.exists(path):
        raise SystemExit("%s is missing at %s -- refusing to report" % (what, os.path.relpath(path, HERE)))
    return open(path, encoding="utf-8").read()


def _advisories(out):
    """The gate's advisory lines, read off the receipt rather than asserted.

    The gate prints two kinds: a **marker** advisory (`WARN:` / `AMBIGUOUS:`) that names a defect
    and still leaves `GATE: PASS` standing, and two **count** advisories (`block form:` and
    `author form:`) whose clean forms are `0 of them not separated` / `<n>/<n>` with no ALL-CAPS
    family token and no character reference.  Both kinds are advisories -- the verdict says nothing
    about either -- so both are classified here and the block reports what it found."""
    markers = [l for l in out.splitlines() if l.strip().startswith(("WARN:", "AMBIGUOUS:"))]
    counts, dirty = {}, []
    m = re.search(r"block form:\s*(\d+) entries,\s*(\d+) of them not separated", out)
    if m:
        counts["block form"] = "%s entries, %s not separated" % (m.group(1), m.group(2))
        if m.group(2) != "0":
            dirty.append("block form")
    m = re.search(r"author form:\s*(\d+)/(\d+)\b(.*)", out)
    if m:
        counts["author form"] = "%s/%s" % (m.group(1), m.group(2))
        rest = m.group(3)
        if m.group(1) != m.group(2) or re.search(r"[1-9]\d* print the family name ALL-CAPS", rest) \
                or re.search(r"[1-9]\d* carry a character reference", rest):
            dirty.append("author form")
    return markers, counts, dirty


def gate_block():
    """The journal gate's output, verbatim, from the committed receipt."""
    out = _receipt(GATE_RECEIPT, "the journal-gate receipt")
    if "GATE:" not in out:
        raise SystemExit("the receipt carries no GATE: verdict line -- it is not the gate's output")
    if "NOT RUN" in out:
        raise SystemExit("the receipt's verdict is NOT RUN -- there is no reading to report")
    markers, counts, dirty = _advisories(out)
    L = [GATE_BEGIN, "",
         "## The journal reference gate (verbatim output)", "",
         "Run from the repository root, on this manuscript, with an interpreter >= 3.12 (the gate's",
         "f-strings carry a backslash):", "",
         "```", GATE_CMD, "```", "",
         "Its **whole** output follows -- the verdict line and every advisory line with it, because",
         "`GATE: PASS` covers only *`entries >= 100`* and *no uncited entries* and says nothing about",
         "the advisories.", ""]
    if markers:
        L += ["**Advisory lines in this run: %d.**" % len(markers), ""]
        L += ["```"] + markers + ["```", "",
              "Each names a form the gate's own selftest admits as a defect that does **not** move the",
              "verdict; none can be cleared by the verdict, so each is read here on its own terms.", ""]
    else:
        L += ["**Marker advisories (`WARN:` / `AMBIGUOUS:`) in this run: 0** -- there is no defect of",
              "that kind to resolve in the reading below.", ""]
    if counts:
        L += ["**The two count advisories are clean in this run**, and they are counts the gate prints",
              "in every run rather than findings (a verdict never clears them): `block form:` reads",
              "`%s` -- every one of the entries stands on its own paragraph for a CommonMark"
              % counts.get("block form", "(absent)"),
              "renderer -- and `author form:` reads `%s` over the entries whose author component is"
              % counts.get("author form", "(absent)"),
              "printed in a form the house style admits at all, with no family token in ALL-CAPS and no",
              "character reference.", ""]
    if dirty:
        L += ["**NOT CLEAN: %s** -- this receipt carries a count advisory whose clean form is not"
              % ", ".join(sorted(dirty)),
              "held; the reading above is not a pass on it.", ""]
    L += ["```", out.rstrip("\n"), "```", "",
          "This block is a committed receipt (`refgate-journal.txt`) re-rendered here by",
          "`make_reference_check.py`; `reproduce.sh` re-runs the gate and compares its output against",
          "the receipt whenever the journal checkout is present, and reports the gate's own named",
          "`NOT RUN` -- exit status 2 -- when the checkout is absent (`refgate.py` reads its window",
          "from its arguments, so this gate runs in an export; the three tree gates take their carrier",
          "set from `git ls-files` and do not).", "",
          GATE_END]
    return "\n".join(L)


def verify_block():
    rec = _receipt(RECEIPT, "the verification receipt")
    if "VERIFIED" not in rec:
        raise SystemExit("the receipt carries no VERIFIED verdict line -- it is not the run's output")
    return "\n".join([
        BEGIN, "",
        "### The verification run (verbatim receipt)", "",
        "Run from `papers/issue-139/`:", "",
        "```", "$ " + CMD, rec.rstrip("\n"), "```", "",
        "The receipt is `refs/verify-run.txt`, committed.  `refscan139.py --gate` fails when the",
        "receipt's `POOL sha256` line no longer matches the shipped `refs/pool.json`, so a receipt",
        "that outlived its pool is caught rather than quoted.", "",
        END,
    ])


def _result_tokens(rec):
    """(verified, mismatch, transport) read off the receipt -- the rows' result column is not typed."""
    m = re.search(r"VERIFIED\s+(\d+)\s*/\s*(\d+)\s*;\s*TITLE MISMATCH\s+(\d+)\s*;\s*"
                  r"TRANSPORT-UNKNOWN\s+(\d+)", rec)
    if not m:
        raise SystemExit("the receipt carries no 'VERIFIED n / n ; TITLE MISMATCH k ; "
                         "TRANSPORT-UNKNOWN j' verdict line -- refusing to render a result column")
    return int(m.group(1)), int(m.group(2)), int(m.group(3)), int(m.group(4))


def _short(title, n=78):
    t = " ".join(title.split())
    return t if len(t) <= n else t[: n - 1].rstrip() + "\u2026"


def entries_block():
    """One row per pool entry: key -> method -> result -> the real record found."""
    pool = json.load(open(POOL, encoding="utf-8"))
    rec = _receipt(RECEIPT, "the verification receipt")
    verified, total, mismatch, transport = _result_tokens(rec)
    if mismatch or transport:
        raise SystemExit("the receipt records %d mismatch / %d transport-unknown -- a row may not "
                         "claim VERIFIED under that verdict" % (mismatch, transport))
    if verified != total or total != len(pool):
        raise SystemExit("the receipt verifies %d/%d over a pool of %d -- the table would not be "
                         "the check it names" % (verified, total, len(pool)))
    L = [ENT_BEGIN, "",
         "## The pool, entry by entry", "",
         "Generated from `refs/pool.json` and the receipt above: **one line per entry**, giving the",
         "citation key, the source registry, the method that verified it, the result, and the real",
         "record the method returned. The **result is rendered from the receipt's verdict**, not",
         "typed: this block refuses to render unless the receipt records a run with no title mismatch",
         "and no transport failure, so a line cannot claim a verification the run did not perform.", "",
         "Each entry is the **source form an entry is READ in** -- one paragraph per entry, so the",
         "rendered page shows one record per entry rather than a horizontal wall (a wide table is a",
         "rendering defect even when its cells are correct).", ""]
    for i, k in enumerate(sorted(pool), 1):
        v = pool[k]
        if v["source"] == "crossref":
            method = "Crossref `works/<doi>` title match"
            link = "https://doi.org/%s" % k
        else:
            method = "arXiv `id_list` title match"
            link = "https://arxiv.org/abs/%s" % k
        L.append("%d. `%s` -- %s -- method: %s -- **VERIFIED** -- record: %s ([%s](%s), %s)"
                 % (i, k, v["source"], method, _short(v["title"], 96), k, link,
                    str(v.get("published", ""))[:4]))
    L += ["", "Every row's `VERIFIED` is the receipt's own verdict over the whole pool; the receipt",
          "is the evidence, this table is its index.  `reference-pool.md` carries the same pool in",
          "reading order with the discovery query that found each entry.", "", ENT_END]
    return "\n".join(L)


def render(path):
    text = open(path, encoding="utf-8").read()
    text = replace_block(text, BEGIN, END, verify_block())
    text = replace_block(text, GATE_BEGIN, GATE_END, gate_block())
    text = replace_block(text, ENT_BEGIN, ENT_END, entries_block())
    return text


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("-")]
    path = args[0] if args else OUT
    if "--check" in argv:
        if render(path) == open(path, encoding="utf-8").read():
            print("reference-check: %s is what this renders" % os.path.basename(path))
            return 0
        print("reference-check: %s DIFFERS from what this renders" % os.path.basename(path))
        return 1
    tmp = path + ".stage"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(render(path))
    os.replace(tmp, path)      # atomic stage-then-replace (Class 201)
    print("wrote %s" % os.path.basename(path))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
