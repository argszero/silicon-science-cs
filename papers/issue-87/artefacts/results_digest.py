#!/usr/bin/env python3
"""#87 -- the results digest: every number the manuscript quotes, read out of a committed artefact.

WHY THIS FILE EXISTS.  A manuscript's numbers are claims about the files beside it, and a number typed into
prose is a claim with no owner.  This file is the owner: it reads the committed result JSONs of the study's
decisive instruments and emits `results_digest.json`, a flat map from a named quantity to the value read out
of the artefact that computed it, with the artefact named.  `manuscript_assembly.py` then asserts that every
value the manuscript prints appears in this digest (and refuses a value that does not), so a stale number in
the prose fails the package's own check instead of a reviewer's.

Every entry is `key -> {"value": ..., "from": "<file>", "path": "<where in that file>"}`.  Nothing here is
generated by the digest: each value is copied out of the artefact's own field, and a field that is absent is
a hard error rather than a default (a digest that invents a number would be the defect it exists to catch).

Run:  /usr/bin/python3 results_digest.py          (numpy is NOT needed; the digest is pure JSON arithmetic)
Writes results_digest.json beside this file.
"""
import io
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INST = os.path.join(HERE, "instruments")
OUT = os.path.join(HERE, "results_digest.json")

D = {}


def load(name):
    with io.open(os.path.join(INST, name), encoding="utf-8") as fh:
        return json.load(fh)


def put(key, value, src, path):
    D[key] = {"value": value, "from": src, "path": path}


def main():
    v5 = load("smoke_v5_results.json")      # the generator, the four rivals, the first single-cell read
    v10 = load("smoke_v10_results.json")    # the joint instrument over the alignment axis (alpha = 1, 0, -1)
    v12 = load("smoke_v12_results.json")    # the base map at alpha = +-1 + the handicap ladder
    v13 = load("smoke_v13_results.json")    # the second graph, the metric's structure, the ladder repair
    v14 = load("smoke_v14_results.json")    # the fallback clause through the calibrated predictive null
    v15 = load("smoke_v15_results.json")    # the q = 8 cell
    v16 = load("smoke_v16_results.json")    # the k = 5 stream panel (the headline)
    r409 = load("r409_align_streams_results.json")   # R409/R412: the 13-stream alignment panel (the review's Q1)
    r412 = load("r412_matchedlocal_tuned_results.json")  # R412: the local rival under the same envelope grid (Q3)

    # ------------------------------------------------- the alignment panel (r409): the review's Q1, answered
    #
    # Every entry here is read out of the instrument that re-measured the alpha = 0 cell over 13 disjoint
    # streams in 3 declared seed families.  The committed cell (alignment.zero_alignment_cells) stays where it
    # is: it is what the submission printed, and the panel's job is to report whether it reproduces.
    _p2 = r409["verdicts"]["P2_pooled_13_streams"]["per_gamma"]
    _p4 = r409["verdicts"]["P4_gap_from_alpha_plus1_negative"]["per_gamma"]
    _xs = r409["cross_stream"]
    put("alignment.panel_gamma1", dict(mean=_p2["1"]["mean"], sd=_p2["1"]["sd"], n=_p2["1"]["n"],
                                       n_negative=_p2["1"]["n_negative"],
                                       t_lo=_xs["shifted|alpha=+0|1"]["t_lo"], t_hi=_xs["shifted|alpha=+0|1"]["t_hi"]),
        "r409_align_streams_results.json", "verdicts.P2_pooled_13_streams.per_gamma[1]")
    put("alignment.panel_gamma2", dict(mean=_p2["2"]["mean"], sd=_p2["2"]["sd"], n=_p2["2"]["n"],
                                       n_negative=_p2["2"]["n_negative"],
                                       t_lo=_xs["shifted|alpha=+0|2"]["t_lo"], t_hi=_xs["shifted|alpha=+0|2"]["t_hi"]),
        "r409_align_streams_results.json", "verdicts.P2_pooled_13_streams.per_gamma[2]")
    put("alignment.panel_n_streams", len(r409["stream_seeds"]), "r409_align_streams_results.json", "stream_seeds")
    put("alignment.panel_seed_families", r409["seed_families"], "r409_align_streams_results.json", "seed_families")
    put("alignment.attenuation", dict(gamma1=dict(mean=_p4["1"]["mean"], n_negative=_p4["1"]["n_negative"],
                                                 n=len(_p4["1"]["per_stream"])),
                                      gamma2=dict(mean=_p4["2"]["mean"], n_negative=_p4["2"]["n_negative"],
                                                  n=len(_p4["2"]["per_stream"]))),
        "r409_align_streams_results.json", "verdicts.P4_gap_from_alpha_plus1_negative.per_gamma")
    put("alignment.six_target_average", dict(gamma1=r409["verdicts"]["P6_six_target_average_keeps_sign"]["gamma1"],
                                             gamma2=r409["verdicts"]["P6_six_target_average_keeps_sign"]["gamma2"],
                                             n_target=r409["six_target"]["shifted"]["1"]["n"]),
        "r409_align_streams_results.json", "verdicts.P6_six_target_average_keeps_sign")
    put("alignment.near_zero_cell_flip", r409["verdicts"]["P5_near_zero_cells_flip"]["cells"][0],
        "r409_align_streams_results.json", "verdicts.P5_near_zero_cells_flip.cells[0]")
    put("alignment.unshifted_stays_positive", r409["verdicts"]["P3_unshifted_stays_positive"],
        "r409_align_streams_results.json", "verdicts.P3_unshifted_stays_positive")
    put("alignment.control_reproduction", dict(all_bitwise=r409["control_P1"]["all_bitwise"],
                                               n_rows=len(r409["control_P1"]["rows"])),
        "r409_align_streams_results.json", "control_P1")
    put("alignment.falsifier_fired", r409["falsifier_fired"], "r409_align_streams_results.json", "falsifier_fired")

    # ------------------------------------------------- the locally matched rival, tuned (r412): the review's Q3
    _s = r412["summary"]
    put("rivals.matchedlocal_tuned", dict(
        s_hat=_s["gamma=0.5"]["s_hat_local_tuned"],
        risk_local_fixed=_s["gamma=0.5"]["risks"]["matchedlocal_fixed"],
        risk_local_tuned=_s["gamma=0.5"]["risks"]["matchedlocal_tuned"],
        risk_matched=_s["gamma=0.5"]["risks"]["matched"],
        risk_quantum=_s["gamma=0.5"]["risks"]["quantum"],
        quantum_minus_tuned=_s["gamma=0.5"]["dQ_minus_local_tuned"]["mean"],
        quantum_minus_matched=_s["gamma=0.5"]["dQ_minus_matched"]["mean"],
        sd_quantum_minus_tuned=_s["gamma=0.5"]["dQ_minus_local_tuned"]["sd"]),
        "r412_matchedlocal_tuned_results.json", "summary.gamma=0.5")
    put("rivals.matchedlocal_blowup", {g: _s["gamma=%g" % g]["risks"]["matchedlocal_tuned"]
                                       for g in (1.0, 2.0)},
        "r412_matchedlocal_tuned_results.json", "summary")
    put("rivals.matchedlocal_trivial_fixed", {g: _s["gamma=%g" % g]["risks"]["matchedlocal_fixed"]
                                              for g in (0.5, 1.0, 2.0)},
        "r412_matchedlocal_tuned_results.json", "summary")
    put("rivals.matchedlocal_n_streams", len(r412["stream_seeds"]), "r412_matchedlocal_tuned_results.json",
        "stream_seeds")
    put("rivals.matchedlocal_usable_cells", r412["verdict"]["cells_with_a_usable_tuned_local_rival"],
        "r412_matchedlocal_tuned_results.json", "verdict.cells_with_a_usable_tuned_local_rival")
    # the mid-band cell at q = 6 (alpha = +1, shifted), as the four arms stand against the SAME matched rival:
    # this is the cell F3's scoping sentence has to name, so it is read here rather than re-typed.
    _mid = None
    for _c in v5["cells"]:
        if abs(_c["alpha"] - 1.0) < 1e-12:
            for _r in _c["rows"]:
                if abs(_r["gamma"] - 0.5) < 1e-12:
                    _mid = _r
    put("rivals.midband_arm_gaps", dict(matched=0.0,
                                        rbf=_mid["risks"]["rbf"]["mean"] - _mid["risks"]["matched"]["mean"],
                                        randfeat=_mid["risks"]["randfeat"]["mean"] - _mid["risks"]["matched"]["mean"],
                                        closedform=_mid["risks"]["closedform"]["mean"] - _mid["risks"]["matched"]["mean"]),
        "smoke_v5_results.json", "cells[alpha=1].rows[gamma=0.5]")

    # ---------------------------------------------------------------- design
    put("design.qubits", v16["qubits"], "smoke_v16_results.json", "qubits")
    put("design.layers", v16["layers"], "smoke_v16_results.json", "layers")
    put("design.gammas", v16["gammas"], "smoke_v16_results.json", "gammas")
    put("design.conventions", v16["convs"], "smoke_v16_results.json", "convs")
    put("design.alphas_base_map", v12["alphas"], "smoke_v12_results.json", "alphas")
    put("design.aligns_joint_instrument", v10["settings"]["aligns"], "smoke_v10_results.json", "settings.aligns")
    put("design.n_streams", len(v16["stream_t0"]), "smoke_v16_results.json", "stream_t0")
    put("design.n_target_per_cell_group", v12["n_target"], "smoke_v12_results.json", "n_target")
    put("design.n_splits", v12["n_splits"], "smoke_v12_results.json", "n_splits")
    put("design.grid_cells_base_map", len(v12["rows"]), "smoke_v12_results.json", "rows")

    # ------------------------------------------- the metric's structure (P1) and the second graph
    put("structure.diag_uniformity_rel_q6", v13["p1_diag_uniformity"],
        "smoke_v13_results.json", "p1_diag_uniformity")
    put("structure.diag_uniformity_rel_q8", v15["diag_uniformity_q8"],
        "smoke_v15_results.json", "diag_uniformity_q8")
    put("structure.cycle_reproduction_of_q6", v13["c7_cycle_reproduction"],
        "smoke_v13_results.json", "c7_cycle_reproduction")

    # ------------------------------------------- the handicap ladder (the registered power arm)
    put("power.ladder_by_axis", v13["p2_axis_effect"], "smoke_v13_results.json", "p2_axis_effect")

    # ------------------------------------------- the advantage map at alpha = +-1, q = 6 (R398 instrument)
    base = {}
    for band, row in sorted(v12["rows"].items()):
        cell = row["cells"]["A_registered|t=0.000"]
        base["%s|a=%+d" % (band, int(row["alpha"]))] = {
            "delta_mean": cell["delta_mean"], "r_rival": cell["r_rival"]}
    put("map_q6.base_map_delta_vs_matched", base, "smoke_v12_results.json", "rows[*].cells['A_registered|t=0.000']")
    put("map_q6.n_cells_quantum_ahead", sum(1 for c in base.values() if c["delta_mean"] < 0),
        "smoke_v12_results.json", "derived: rows[*] delta_mean < 0")

    # ------------------------------------------- the k = 5 stream panel (the headline, R402)
    cells = {}
    for name, c in sorted(v16["cells"].items()):
        cells[name] = {k: c[k] for k in ("mean6", "sd6", "mean8", "sd8", "sign6", "sign8",
                                         "unanimity6", "unanimity8")}
    put("panel.cells", cells, "smoke_v16_results.json", "cells")
    put("panel.q1_structure_stable", v16["q1_structure_stable"], "smoke_v16_results.json",
        "q1_structure_stable")
    put("panel.q2_near_zero_unresolved", v16["q2_near_zero_unresolved"], "smoke_v16_results.json",
        "q2_near_zero_unresolved")
    put("panel.q3_attenuation", v16["q3_attenuation"], "smoke_v16_results.json", "q3_attenuation")
    put("panel.q4_main_claim_ci", v16["q4_main_claim_ci"], "smoke_v16_results.json", "q4_main_claim_ci")
    put("panel.q5_stream_vs_draw", v16["q5_stream_vs_draw"], "smoke_v16_results.json", "q5_stream_vs_draw")
    put("panel.q6_matched_vs_rbf", v16["q6_matched_vs_rbf"], "smoke_v16_results.json", "q6_matched_vs_rbf")
    put("panel.quantum_ahead_per_stream", v16["quantum_leads_per_stream"], "smoke_v16_results.json",
        "quantum_leads_per_stream")
    put("panel.controls", v16["controls"], "smoke_v16_results.json", "controls")
    r = [v16["cells"][k]["mean8"] / v16["cells"][k]["mean6"] for k in v16["structure_set"]]
    put("panel.q8_over_q6_ratio_of_the_mid_band", {
        "mean": sum(r) / len(r), "median": statistics.median(r), "min": min(r), "max": max(r)},
        "smoke_v16_results.json", "derived: cells[*].mean8 / cells[*].mean6 over structure_set")
    put("panel.stream_seeds", v16["stream_t0"], "smoke_v16_results.json", "stream_t0")
    # Q5's repair: the registered inequality compared a stream-MEAN sd against a single-draw sd, so the
    # denominator was mis-specified (under iid draws it should be sigma_draw/sqrt(6)).  The addendum measures
    # the matched denominator on the panel's own code path.
    ds = load("r402_drawspread_results.json")
    q5 = {}
    for qq in ("6", "8"):
        rat = sorted(ds["ratio"][qq]["ratio"].values())
        q5["q" + qq] = {
            "median_ratio": statistics.median(rat), "min_ratio": rat[0], "max_ratio": rat[-1],
            "n_above_1p2": ds["ratio"][qq]["n_above_1p2"],
            "sigma_draw": statistics.mean(
                v for cell in ds["draw_spreads"][qq].values() for v in cell.values())}
    q5["iid_benchmark_1_over_sqrt6"] = ds["bench"]
    put("panel.q5_repair_matched_denominator", q5, "r402_drawspread_results.json",
        "ratio[*], draw_spreads[*], bench")

    # ------------------------------------------- the fallback clause (calibrated predictive null)
    obs = v14["observed"]
    lvl = {}
    for cell, o in sorted(obs.items()):
        lvl[cell] = {t: o["cells"][t]["mean"] for t in o["cells"]}
    put("fallback.per_cell_delta_by_handicap_level", lvl, "smoke_v14_results.json",
        "observed[*].cells[*].mean")
    put("fallback.declared_at_t0", {"n_cells": v14["power"]["t=0.000"]["n_cells"],
                                    "n_declared": v14["power"]["t=0.000"]["n_declared"],
                                    "median_delta": v14["power"]["t=0.000"]["median_delta"]},
        "smoke_v14_results.json", "power['t=0.000']")
    put("fallback.declared_at_t1", {"n_cells": v14["power"]["t=1.000"]["n_cells"],
                                    "n_declared": v14["power"]["t=1.000"]["n_declared"],
                                    "median_delta": v14["power"]["t=1.000"]["median_delta"]},
        "smoke_v14_results.json", "power['t=1.000']")
    put("fallback.resolution_floor", min(v14["resolution_floor"].values()), "smoke_v14_results.json",
        "resolution_floor")
    put("fallback.bh_threshold_min", v14["power"]["t=0.000"]["bh_threshold_min"],
        "smoke_v14_results.json", "power['t=0.000'].bh_threshold_min")
    put("fallback.n_null_draws_used", v14["n_null"], "smoke_v14_results.json", "n_null")
    worst1 = sorted(lvl.items(), key=lambda kv: -kv[1]["1.0"])[:4]
    put("fallback.four_worst_cells_at_t1", {k: v["1.0"] for k, v in worst1},
        "smoke_v14_results.json", "observed[*].cells['1.0'].mean")
    put("fallback.size_on_holdout_null", v14["size_holdout"], "smoke_v14_results.json", "size_holdout")
    put("fallback.declared_count_by_level",
        {t: v14["power"][t]["n_declared"] for t in sorted(v14["power"])},
        "smoke_v14_results.json", "power[*].n_declared")
    # the power keys are 't=0.000' and the observed cells are keyed by the level's own float string; the two
    # are joined through the level's VALUE (a join by spelling would silently drop a level).
    first_cell = next(iter(lvl.values()))
    lvl_key = {round(float(k), 3): k for k in first_cell}
    if sorted(lvl_key) != sorted(round(float(t.split("=")[1]), 3) for t in v14["power"]):
        raise SystemExit("the power levels and the observed levels do not name the same levels: %r vs %r"
                         % (sorted(lvl_key), sorted(v14["power"])))
    put("fallback.lead_count_by_level",
        {t: sum(1 for c in lvl.values() if c[lvl_key[round(float(t.split("=")[1]), 3)]] < 0)
         for t in sorted(v14["power"])},
        "smoke_v14_results.json", "derived: observed[*].cells[level].mean < 0")
    put("fallback.max_declared_p_at_t0", v14["power"]["t=0.000"]["max_p_declared"],
        "smoke_v14_results.json", "power['t=0.000'].max_p_declared")

    # ------------------------------------------- the path stratum: the map on the second graph, and the PSD repair
    pa = v13["path_audit"]
    path_t0, sign_agree = {}, 0
    for band, row in sorted(pa["rows"].items()):
        d = row["cells"]["A_registered|t=0.000"]["delta_mean"]
        cyc = v13["cycle_audit"]["rows"][band]["cells"]["A_registered|t=0.000"]["delta_mean"]
        path_t0["%s|a=%+d" % (band, int(row["alpha"]))] = d
        if (d < 0) == (cyc < 0):
            sign_agree += 1
    put("structure.path_map_delta_vs_matched", path_t0, "smoke_v13_results.json",
        "path_audit.rows[*].cells['A_registered|t=0.000']")
    put("structure.path_map_sign_agreement_with_cycle", {"agree": sign_agree, "of": len(path_t0)},
        "smoke_v13_results.json", "derived: sign(path_audit rows) == sign(cycle_audit rows)")
    add = [r["added_rel_mean_diag"] for r in pa["psd_repairs"]]
    sc = [r["scale"] for r in pa["psd_repairs"]]
    put("power.psd_repair_on_the_path", {
        "n_repairs": len(pa["psd_repairs"]),
        "min_eig_before_min": min(r["min_eig_before"] for r in pa["psd_repairs"]),
        "added_rel_mean_diag_range": [min(add), max(add)],
        "scale_range": [min(sc), max(sc)]},
        "smoke_v13_results.json", "path_audit.psd_repairs")

    # ------------------------------------------- the alignment axis (alpha = 0), shifted vs unshifted
    al = {"shifted": {}, "unshifted": {}}
    for row in v10["rows"]:
        if row["alpha"] == 0.0:
            al[row["conv"]]["%g" % row["gamma"]] = {
                "delta_mean": row["delta_mean"], "p_predictive": row["p_predictive"],
                "q_predictive": row["q_predictive"], "sign": row["sign"]}
    put("alignment.zero_alignment_cells", al, "smoke_v10_results.json", "rows[alpha == 0]")
    put("alignment.fdr_predictive", v10["fdr"]["predictive"], "smoke_v10_results.json",
        "fdr.predictive")

    # ------------------------------------------- the rival's identity decides the verdict
    g = {}
    for cell in v5["cells"]:
        for row in cell["rows"]:
            g["%s|%g" % ("alpha=%+d" % int(cell["alpha"]), row["gamma"])] = {
                "risks": {a: row["risks"][a]["mean"] for a in
                          ("quantum", "matched", "rbf", "randfeat", "closedform", "product", "oracle")},
                "delta_vs_matched": {a: row["delta_vs_matched"][a]["mean"] for a in
                                     ("quantum", "rbf", "randfeat", "closedform", "product")},
                "aliveness_mean_offdiag": row["aliveness"]["mean_offdiag"],
                "metric_spread": row["metric_spread"]}
    put("rivals.risks_and_deltas", g, "smoke_v5_results.json", "cells[*].rows[*]")
    q05 = [g[k] for k in g if k.endswith("|0.5") and k.startswith("alpha=+1")]
    if q05:
        rr = q05[0]["risks"]
        put("rivals.gamma_0p5_arm_risks", rr, "smoke_v5_results.json", "cells[alpha=1].rows[gamma=0.5]")
        put("rivals.gamma_0p5_quantum_minus_random_feature",
            rr["quantum"] - rr["randfeat"], "smoke_v5_results.json",
            "derived: risks.quantum - risks.randfeat at gamma=0.5")
    # the difference the manuscript quotes is the QUANTUM arm minus each rival (the tables' Delta columns);
    # the artefact stores each arm's own delta against the matched rival, so the derived pair is computed here
    # rather than typed into the prose.
    qm = {}
    for gamma in ("0.1", "0.25", "0.5", "1", "2", "3"):
        rec = g["alpha=+1|%s" % gamma]["risks"]
        qm[gamma] = {a: rec["quantum"] - rec[a]
                     for a in ("matched", "rbf", "randfeat", "closedform", "product", "oracle")}
    put("rivals.quantum_minus_arm", qm, "smoke_v5_results.json",
        "derived: risks.quantum - risks[arm] over cells[alpha=1].rows[gamma]")
    put("rivals.closedform_minus_matched_gamma_0p5",
        abs(g["alpha=+1|0.5"]["risks"]["closedform"] - g["alpha=+1|0.5"]["risks"]["matched"]),
        "smoke_v5_results.json", "derived: |risks.closedform - risks.matched| at alpha=1, gamma=0.5")

    # ------------------------------------------- controls that could have failed
    put("controls.v5", v5["controls"], "smoke_v5_results.json", "controls")
    put("controls.v12", v12["controls"], "smoke_v12_results.json", "controls")
    put("controls.v13_path_determinism", v13["path_determinism"], "smoke_v13_results.json",
        "path_determinism")
    put("controls.v15_determinism", v15["determinism"], "smoke_v15_results.json", "determinism")
    put("v15.matched_minus_rbf", v15["matched_minus_rbf"], "smoke_v15_results.json", "matched_minus_rbf")
    put("v15.aliveness", v15["aliveness"], "smoke_v15_results.json", "aliveness")

    with io.open(OUT, "w", encoding="utf-8") as fh:
        fh.write(json.dumps({"round": "R405", "source": "papers/issue-87/artefacts/instruments/*.json",
                             "n_quantities": len(D), "quantities": D}, indent=1, sort_keys=True))

    print("results_digest.json: %d quantities read out of the committed artefacts" % len(D))
    for k in sorted(D):
        v = D[k]["value"]
        s = json.dumps(v)
        print("  %-46s %s%s" % (k, s[:96], " ..." if len(s) > 96 else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
