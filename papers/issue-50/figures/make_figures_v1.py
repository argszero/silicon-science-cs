# One planted change per figure, applied to a throwaway copy of the artefacts.  The mutation names the
# number the figure draws -- so a figure whose liveness case does not fire is a figure that is not
# reading that number, whatever its caption says.
MUTATIONS = [
    ("fig1_boundary.svg", "boundary_v2_h100.json", ("families", 0, "rows", 0, "benefit_pct"), 3.0),
    ("fig3_prediction.svg", "variant_v1.json", ("cells", 0, "F", "mean"), 0.11),
    ("fig2_tail.svg", "tail_v1_h100.json", ("p2_first_half", "per_family", 0, "heavy", "x_star"), 0.001),
    ("fig4_mixture.svg", "sideeffect_v1.json", ("m4b", 0, "cells", 0, "frac_negative"), 0.05),
]


def build(name, art):
    fn = dict(FIGURES)[name]
    facts = {}
    return fn(art, facts), facts


def planted(dirname, name, path, delta):
    """A copy of the artefacts with one number moved, by `path` into that file's JSON."""
    tmp = os.path.join(dirname, os.path.basename(name))
    doc = json.load(io.open(os.path.join(DEFAULT_ARTS, name), encoding="utf-8"))
    node = doc
    for key in path[:-1]:
        node = node[key]
    leaf = path[-1]
    was = node[leaf]
    node[leaf] = (was + delta) if isinstance(was, (int, float)) else delta
    io.open(tmp, "w", encoding="utf-8").write(json.dumps(doc, indent=1, sort_keys=True))
    return tmp, was


def selftest():
    """One planted change per figure, plus the base case: the base case must PASS, or the four
    mutations prove nothing about the reader (they would fail for any input)."""
    bad = 0
    art = read_artefacts()
    for name, _ in FIGURES:
        text, _f = build(name, art)
        path = os.path.join(HERE, name)
        have = io.open(path, encoding="utf-8").read() if os.path.exists(path) else None
        ok = have == text
        if not ok:
            bad += 1
        print("  base  %-20s %s" % (name, "the committed bytes are what the artefacts say" if ok
                                    else "DIFFERS from the committed figure"))
    tmpdir = tempfile.mkdtemp(prefix="issue50-fig-")
    try:
        for fig, owner, path, delta in MUTATIONS:
            d = os.path.join(tmpdir, fig)
            os.makedirs(d)
            # the mutation goes into a COMPLETE copy of the artefacts -- read_artefacts() opens all
            # four files, and a directory holding only the mutated one would fail for the wrong reason
            for nm in READS:
                if nm != owner:
                    shutil.copyfile(os.path.join(DEFAULT_ARTS, nm), os.path.join(d, nm))
            _tmp, was = planted(d, owner, path, delta)
            mutated = read_artefacts(d)
            text, _f = build(fig, mutated)
            base, _f2 = build(fig, read_artefacts())
            fires = text != base
            print("  plant %-20s %s: %s -> %s ... %s"
                  % (fig, owner, was, was + delta,
                     "the figure moved" if fires else "THE FIGURE DID NOT MOVE (control void)"))
            if not fires:
                bad += 1
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)
    puts = {"reads": len(READS), "cases": len(MUTATIONS) + len(FIGURES)}
    print("FIGURES SELFTEST: %d case(s), %d not firing" % (puts["cases"], bad))
    return 0 if bad == 0 else 1


def main():
    check = "--check" in sys.argv
    art = read_artefacts()
    bad = 0
    for name, _fn in FIGURES:
        text, facts = build(name, art)
        path = os.path.join(HERE, name)
        if check:
            have = io.open(path, encoding="utf-8").read() if os.path.exists(path) else None
            same = have == text
            print("  %-4s %-22s %6d B  sha %s" % ("ok" if same else "DIFF", name, len(text),
                                                 hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]))
            if not same:
                bad += 1
        else:
            io.open(path, "w", encoding="utf-8").write(text)
            print("  wrote %-22s %6d B  %d value(s) drawn" % (name, len(text), len(facts)))
    if check:
        print("FIGURES: %d of %d regenerated byte-identical from the artefacts"
              % (len(FIGURES) - bad, len(FIGURES)))
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    if "--facts" in sys.argv:
        art = read_artefacts()
        allfacts = {}
        for name, _fn in FIGURES:
            _t, f = build(name, art)
            allfacts.update(f)
        print(json.dumps(allfacts, indent=1, sort_keys=True))
        sys.exit(0)
    sys.exit(main())
