#!/usr/bin/env python3
"""Issue #50 -- the four figures, written as SVG by this file and by nothing else.

    python3 figures/make_figures_v1.py            # write figures/*.svg from the artefacts
    python3 figures/make_figures_v1.py --check    # regenerate and compare byte for byte
    python3 figures/make_figures_v1.py --facts    # print every value the four figures draw
    python3 figures/make_figures_v1.py --selftest # liveness: one planted change per figure must show

WHY THE FIGURES ARE WRITTEN HERE INSTEAD OF PLOTTED.  Section 3 of the manuscript claims the instrument
is deterministic and its evidence needs a Python interpreter and nothing else.  A figure drawn through
a plotting library would make that claim false for a reader who has to install one, and it would make
the figure's own bytes a function of a library version -- so `--check` could no longer compare them the
way it compares every other artefact.  Writing the SVG here keeps all four figures on the same footing
as the JSON: bytes a rerun must reproduce exactly.

WHAT EACH FIGURE IS, AND WHO OWNS EVERY COORDINATE IT DRAWS:

  fig1_boundary.svg    mean per-step benefit against measured contention, one series per pool size at
                       h = 1.0, with each family's located crossing marked.
                       owner: artefacts/boundary_v2_h100.json -- section 4's boundary.
  fig3_prediction.svg  F, and the blind arm's share 1 - F, against the speculation width h, at the pool
                       sizes that differ.  owner: artefacts/variant_v1.json -- section 4's
                       matched-parallelism control and section 8's answer to "worse than nothing".
  fig2_tail.svg        the registered P2 claim, refuted: mean-matched heavy and light classes, their
                       located boundaries with intervals, and the paired difference per family.
                       owner: artefacts/tail_v1_h100.json.
  fig4_mixture.svg     the step-level reading at the boundary cells: the share of steps whose benefit is
                       negative, with its interval.  owner: artefacts/sideeffect_v1.json.

No number is typed into a figure: every coordinate comes out of the artefact named above, read by the
one `read_artefacts()` that `--facts` and the liveness control also go through.  `--selftest` plants one
change per figure in a throwaway copy of the artefacts and requires the regenerated bytes to differ -- a
figure that would not notice a changed input is a picture of the author's memory rather than a reading.
"""
